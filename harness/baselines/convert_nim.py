"""The Nim dialect of convert_foreign.py: the harness types as objects of
nim-ssz-serialization (Nimbus). One module holds both presets; the types of
a preset other than the first carry the preset's name as a suffix
(FuluBeaconStateMinimal), since Nim's generic sizes and limits are
compile-time and the two presets must be distinct types.

    List[T, limit]        a list          array[n, T]      a vector
    BitList[limit]        a bitlist       BitArray[bits]   a bitvector
    seq[T]                a progressive list (the library's uncached form)
    BitSeq                a progressive bitlist
    {.sszActiveFields.}   a progressive container (every field active)
    UInt256 (stint)       uint256         array[n, byte]   a byte vector
"""
from convert_foreign import shape


def nim_base(base, suffix):
    kind = base[0]
    if kind == 'uint':
        return f'uint{base[1]}'
    if kind == 'bool':
        return 'bool'
    if kind == 'bytes':
        return f'array[{base[1]}, byte]'
    if kind == 'struct':
        return base[1] + suffix
    if kind == 'u256':
        return 'UInt256'
    if kind == 'bitvector':
        return f'BitArray[{base[1]}]'
    if kind == 'bitlist':
        return f'BitList[{base[1]}]'
    if kind == 'pbitlist':
        return 'BitSeq'
    raise ValueError(base)


def nim_type(sh, suffix):
    t = nim_base(sh.base, suffix)
    for kind, n in reversed(sh.levels):
        if kind == 'vector':
            t = f'array[{n}, {t}]'
        elif kind == 'list':
            t = f'List[{t}, {n}]'
        else:
            t = f'seq[{t}]'
    return t


def emit(aliases, structs, order, keep, presets):
    out = ['# Generated by baselines/convert_foreign.py from the harness types: do not edit.',
           '', 'import ssz_serialization', '', 'export ssz_serialization', '']
    for i, preset in enumerate(presets):
        # The first preset keeps the harness names; the others are suffixed.
        suffix = '' if i == 0 else preset.name.capitalize()
        out.append(f'# Preset {preset.name}.')
        out.append('type')
        for name in order:
            if name not in keep:
                continue
            fields = structs[name]
            progressive = any('ssz-index' in t for _, _, t in fields)
            if progressive:
                active = ', '.join('1' for _ in fields)
                out.append(f'  {name}{suffix}* {{.sszActiveFields: [{active}].}} = object')
            else:
                out.append(f'  {name}{suffix}* = object')
            for fname, typ, tags in fields:
                out.append(f'    {fname}*: {nim_type(shape(typ, tags, aliases, preset), suffix)}')
            out.append('')
    return '\n'.join(out)
