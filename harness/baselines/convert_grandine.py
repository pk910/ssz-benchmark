import re
"""The Grandine dialect of convert_foreign.py: the harness types as Rust
structs deriving Grandine's `Ssz` (grandinetech/grandine, crate ssz), one
module per preset with the preset's sizes and limits as typenum constants.

Containers: `ContiguousList<T, N>`, `ContiguousVector<T, N>` (inline, a
GenericArray), `ByteList<N>` / `ByteVector<N>` for byte lists and vectors,
`BitList<N>` / `BitVector<N>`, `ProgressiveList<T>` (no limit in the
crate), `ProgressiveBitList<N>` and `ProgressiveByteList<N>` (the crate
keeps a limit parameter that only bounds the decoder), `Uint256`, and the
fixed hashes H32/H160/H256/H384 for the 4, 20, 32 and 48 byte arrays as
Grandine's own types use them. A struct with `ssz-index` fields is a
progressive container: `#[ssz(stable(active = [1; n]))]`.
"""
from convert_foreign import shape

# The limit of a progressive bit or byte list the harness leaves unbounded:
# the crate's `ProgressiveList` has none, its bit and byte lists keep one
# that only bounds the decoder, so the largest Grandine itself uses
# (MAX_BYTES_PER_TRANSACTION) stands in. The root does not depend on it.
UNBOUNDED = 1073741824

# The fixed hash types the crate implements SSZ for (ssz/src/arrays.rs).
FIXED_HASH = {4: 'H32', 20: 'H160', 32: 'H256', 48: 'H384'}


def typenum(n):
    """typenum names U0..U1024 and the powers of two; any other number is
    spelled as its binary UInt chain, which every typenum operation takes."""
    if n <= 1024 or n & (n - 1) == 0:
        return f'U{n}'
    t = 'UTerm'
    for bit in bin(n)[2:]:
        t = f'UInt<{t}, B{bit}>'
    return t


def base_type(base):
    kind = base[0]
    if kind == 'uint':
        return f'u{base[1]}'
    if kind == 'bool':
        return 'bool'
    if kind == 'bytes':
        return FIXED_HASH.get(base[1], f'ByteVector<{typenum(base[1])}>')
    if kind == 'struct':
        return base[1]
    if kind == 'u256':
        return 'Uint256'
    if kind == 'bitvector':
        return f'BitVector<{typenum(base[1])}>'
    if kind == 'bitlist':
        return f'BitList<{typenum(base[1])}>'
    if kind == 'pbitlist':
        return f'ProgressiveBitList<{typenum(UNBOUNDED)}>'
    raise ValueError(base)


def rust_type(sh):
    """The levels from the innermost out; a list level directly over bytes
    is a byte list (a vector over bytes was folded into the base by shape)."""
    t = base_type(sh.base)
    for i, (kind, n) in reversed(list(enumerate(sh.levels))):
        innermost = i == len(sh.levels) - 1
        if innermost and sh.base == ('uint', 8) and kind == 'list':
            t = f'ByteList<{typenum(n)}>'
        elif innermost and sh.base == ('uint', 8) and kind == 'plist':
            t = f'ProgressiveByteList<{typenum(n or UNBOUNDED)}>'
        elif kind == 'vector':
            t = f'ContiguousVector<{t}, {typenum(n)}>'
        elif kind == 'list':
            t = f'ContiguousList<{t}, {typenum(n)}>'
        else:
            t = f'ProgressiveList<{t}>'
    return t


def emit(aliases, structs, order, keep, presets):
    out = ['// Generated by baselines/convert_foreign.py grandine from the harness types: do not edit.',
           '#![allow(non_snake_case, dead_code, unused_imports, clippy::all)]', '']
    for preset in presets:
        out.append(f'pub mod {preset.name} {{')
        out.append('    use ethereum_types::{H160, H256, H32};')
        out.append('    use primitive_types::H384;')
        # The progressive types are imported only when a type uses them: a
        # library version without them still builds the other fork.
        imports_at = len(out)
        out.append(None)
        out.append('    use ssz::{BitList, BitVector, ByteList, ByteVector, ContiguousList, ContiguousVector, Ssz, Uint256};')
        out.append('    use typenum::consts::*;')
        out.append('    use typenum::{UInt, UTerm, B0, B1};')
        out.append('')
        for name in order:
            if name not in keep:
                continue
            fields = structs[name]
            progressive = any('ssz-index' in t for _, _, t in fields)
            out.append('    #[derive(Debug, Clone, PartialEq, Ssz)]')
            if progressive:
                out.append(f'    #[ssz(stable(active = [1; {len(fields)}]))]')
            out.append(f'    pub struct {name} {{')
            for fname, typ, tags in fields:
                out.append(f'        pub {fname}: {rust_type(shape(typ, tags, aliases, preset))},')
            out.append('    }')
            out.append('')
        body = '\n'.join(line for line in out[imports_at + 1:] if line is not None)
        names = [n for n in ('ProgressiveBitList', 'ProgressiveByteList', 'ProgressiveList') if re.search(r'\b' + n + r'\b', body)]
        out[imports_at] = '    use ssz::{' + ', '.join(names) + '};' if names else '    // no progressive types in this fork'
        out.append('}')
        out.append('')
    return '\n'.join(out)
