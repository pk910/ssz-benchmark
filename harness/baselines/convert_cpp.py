"""The C++ dialect of convert_foreign.py for sszpp (OffchainLabs/sszpp): one
namespace per preset with the harness structs as ssz++ containers.

The mapping of a shape: uintN to std::uintN_t, bool to bool, a byte vector
to std::array<std::byte, n>, uint256 to intx::uint256 (a basic type of the
library, 32 little-endian bytes), a bitvector to std::bitset<bits>, a
bitlist to ssz::list<bool, limit>, a vector to std::array<T, n> and a list
to ssz::list<T, limit>. A struct inherits ssz::ssz_container when every
field is fixed size and ssz::ssz_variable_size_container otherwise, and
lists its members in SSZ_CONT, which gives it ssz_size, serialize,
deserialize and hash_tree_root. The structs are written in dependency order
(C++ needs a member's type complete), their names qualified with the
namespace so that a field named like its type (Fork Fork) does not change
the meaning of the name inside the struct.

Progressive lists, bitlists and containers (the Gloas types) have no
equivalent in sszpp: emit() raises for them, and the build generates the
Fulu types only.
"""
from convert_foreign import shape

HEADER = '''// Generated by baselines/convert_foreign.py from the harness types: do not edit.
#pragma once
#include <array>
#include <bitset>
#include <cstdint>
#include <intx/intx.hpp>
#include <ssz++.hpp>
'''


def cpp_base(base, ns):
    kind = base[0]
    if kind == 'uint':
        return f'std::uint{base[1]}_t'
    if kind == 'bool':
        return 'bool'
    if kind == 'bytes':
        return f'std::array<std::byte, {base[1]}>'
    if kind == 'struct':
        return f'{ns}::{base[1]}'
    if kind == 'u256':
        return 'intx::uint256'
    if kind == 'bitvector':
        return f'std::bitset<{base[1]}>'
    if kind == 'bitlist':
        return f'ssz::list<bool, {base[1]}>'
    raise ValueError(f'sszpp cannot express {kind}')


def cpp_type(sh, ns):
    t = cpp_base(sh.base, ns)
    for kind, n in reversed(sh.levels):
        if kind == 'vector':
            t = f'std::array<{t}, {n}>'
        elif kind == 'list':
            t = f'ssz::list<{t}, {n}>'
        else:
            raise ValueError(f'sszpp cannot express a {kind}')
    return t


def dependency_order(structs, aliases, keep, order, preset):
    """The kept structs with every struct before the ones that hold it."""
    out, done = [], set()

    def visit(name):
        if name in done:
            return
        done.add(name)
        for _, typ, tags in structs[name]:
            sh = shape(typ, tags, aliases, preset)
            if sh.base[0] == 'struct' and sh.base[1] in structs:
                visit(sh.base[1])
        out.append(name)
    for name in order:
        if name in keep:
            visit(name)
    return out


def variable_size(structs, aliases, preset):
    """Whether each struct has a variable SSZ size: a list, a bitlist or a
    variable-size struct anywhere in a field (a vector of variable-size
    elements is variable too)."""
    memo = {}

    def var(name):
        if name in memo:
            return memo[name]
        memo[name] = False
        for _, typ, tags in structs[name]:
            sh = shape(typ, tags, aliases, preset)
            if any(kind != 'vector' for kind, _ in sh.levels) or sh.base[0] in ('bitlist', 'pbitlist'):
                memo[name] = True
            elif sh.base[0] == 'struct' and sh.base[1] in structs and var(sh.base[1]):
                memo[name] = True
        return memo[name]
    return var


def emit(aliases, structs, order, keep, presets):
    out = [HEADER]
    for preset in presets:
        ns = preset.name
        is_variable = variable_size(structs, aliases, preset)
        out.append(f'namespace {ns} {{')
        out.append('')
        for name in dependency_order(structs, aliases, keep, order, preset):
            fields = structs[name]
            if any('ssz-index' in tags for _, _, tags in fields):
                raise ValueError(f'{name} is a progressive container, which sszpp cannot express')
            base = 'ssz::ssz_variable_size_container' if is_variable(name) else 'ssz::ssz_container'
            out.append(f'struct {name} : {base} {{')
            for fname, typ, tags in fields:
                out.append(f'    {cpp_type(shape(typ, tags, aliases, preset), ns)} {fname};')
            out.append(f'    SSZ_CONT({", ".join(f for f, _, _ in fields)});')
            out.append('};')
            out.append('')
        out.append(f'}}  // namespace {ns}')
        out.append('')
    return '\n'.join(out)
