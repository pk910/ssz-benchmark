"""The Java dialect of convert_foreign.py: the harness types as Teku SSZ
schemas (tech.pegasys.teku.infrastructure.ssz), built at class
initialisation with the sizes and limits of a preset already evaluated.

One file per fork holds one package-private class per preset,
Gen<Fork><Preset> (GenFuluMainnet, GenFuluMinimal, ...), whose static
fields are the container schemas named after the Go structs. The schema
expressions use the helpers of bench/Schemas.java (container, progressive,
list, vector, plist, bytes, ...), so a field reads as its shape:
`list(vector(bytes(32), 33), 16)`. Java resolves static initialisers in
textual order, so the structs come out in dependency order.
"""
from convert_foreign import shape

# The forks the harness types are named after, newest first: the fork of a
# file is the newest one with a state among the kept structs.
FORKS = ['Gloas', 'Fulu', 'Electra', 'Deneb', 'Capella', 'Bellatrix', 'Altair']


def java_base(base):
    kind = base[0]
    if kind == 'uint':
        if base[1] == 8:
            return 'U8'
        if base[1] == 64:
            return 'U64'
        raise ValueError(f'uint{base[1]} has no Teku schema here')
    if kind == 'bool':
        return 'BOOL'
    if kind == 'bytes':
        return f'bytes({base[1]})'
    if kind == 'struct':
        return base[1]
    if kind == 'u256':
        return 'U256'
    if kind == 'bitvector':
        return f'bitvector({base[1]})'
    if kind == 'bitlist':
        return f'bitlist({base[1]}L)'
    if kind == 'pbitlist':
        return 'pbitlist()'
    raise ValueError(base)


def java_type(sh):
    t = java_base(sh.base)
    for kind, n in reversed(sh.levels):
        if kind == 'vector':
            t = f'vector({t}, {n}L)'
        elif kind == 'list':
            t = f'list({t}, {n}L)'
        else:
            t = f'plist({t})'
    return t


def dependency_order(structs, order, keep, aliases, preset):
    """The kept structs with every struct before the structs that refer to
    it, source order otherwise."""
    out, done = [], set()

    def visit(name):
        if name in done:
            return
        done.add(name)
        for _, typ, tags in structs[name]:
            base = shape(typ, tags, aliases, preset).base
            if base[0] == 'struct' and base[1] in keep:
                visit(base[1])
        out.append(name)
    for name in order:
        if name in keep:
            visit(name)
    return out


def emit(aliases, structs, order, keep, presets):
    fork = next(f for f in FORKS if f + 'BeaconState' in keep)
    out = ['// Generated by baselines/convert_foreign.py from the harness types: do not edit.',
           'package bench;', '',
           'import static bench.Schemas.*;', '',
           'import tech.pegasys.teku.infrastructure.ssz.SszContainer;',
           'import tech.pegasys.teku.infrastructure.ssz.schema.SszContainerSchema;', '']
    for preset in presets:
        cls = f'Gen{fork}{preset.name.capitalize()}'
        out.append(f'/** The {fork} types with the sizes and limits of the {preset.name} preset. */')
        out.append(f'final class {cls} {{')
        out.append(f'  private {cls}() {{}}')
        out.append('')
        for name in dependency_order(structs, order, keep, aliases, preset):
            fields = structs[name]
            progressive = any('ssz-index' in t for _, _, t in fields)
            ctor = 'progressive' if progressive else 'container'
            out.append(f'  static final SszContainerSchema<SszContainer> {name} = {ctor}("{name}",')
            for i, (fname, typ, tags) in enumerate(fields):
                sep = ');' if i + 1 == len(fields) else ','
                out.append(f'      f("{fname}", {java_type(shape(typ, tags, aliases, preset))}){sep}')
            out.append('')
        out.append('}')
        out.append('')
    return '\n'.join(out)
