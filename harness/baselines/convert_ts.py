"""The JavaScript dialect of convert_foreign.py for @chainsafe/ssz (Lodestar's
SSZ): the harness types as type objects composed at runtime, one exported
object per preset with the spec sizes already evaluated.

    convert_foreign.py ts <types.go> <out.mjs> --roots A,B --preset name=spec.json [...]

The generated module imports the built package from the adapter's work/
checkout and exports `mainnet` and `minimal` (the presets given), each a
map of struct name to type. A struct with ssz-index fields becomes a
ProgressiveContainerType with every field active; a progressive-list
level a Progressive*ListType; a list of Go bytes a ByteListType (a list
of uint8 that is not bytes, such as participation flags, stays a
ListBasicType, which serializes and merkleizes the same). uint64 fields
are UintNumberType(8) with clipInfinity, as Lodestar's own types read
epochs: 2^64-1 (the far-future epoch of every active validator) rounds
to 2^64 as a double and would not serialize back, Infinity does.
"""
import re

from convert_foreign import shape

# The import of the built package, relative to src/ in the adapter.
SSZ_IMPORT = '../work/ssz/packages/ssz/lib/index.js'


def is_bytes(typ, aliases):
    """Whether the element under every slice/array level of a Go type is
    `byte` (as opposed to uint8, which the Go types use for flags)."""
    typ = typ.lstrip('*')
    seen = set()
    while True:
        if typ in aliases and typ not in seen:
            seen.add(typ)
            typ = aliases[typ]
            continue
        m = re.match(r'^\[\d*\](.*)$', typ)
        if not m:
            break
        typ = m.group(1).lstrip('*')
        seen = set()
    return typ == 'byte'


def js_base(base):
    kind = base[0]
    if kind == 'uint':
        return f'uint{base[1]}'
    if kind == 'bool':
        return 'boolean'
    if kind == 'bytes':
        return f'new ssz.ByteVectorType({base[1]})'
    if kind == 'struct':
        return base[1]
    if kind == 'u256':
        return 'uint256'
    if kind == 'bitvector':
        return f'new ssz.BitVectorType({base[1]})'
    if kind == 'bitlist':
        return f'new ssz.BitListType({base[1]})'
    if kind == 'pbitlist':
        return 'new ssz.ProgressiveBitListType()'
    raise ValueError(base)


def js_type(sh, bytes_elem):
    """The expression of a field's type: the levels wrapped around the
    base from the innermost out. The innermost level over bytes is a byte
    list (a byte vector is already the base); a level over a basic base
    with nothing between is a basic array, anything else composite."""
    t = js_base(sh.base)
    basic = sh.base[0] in ('uint', 'bool', 'u256')
    for i, (kind, n) in enumerate(reversed(sh.levels)):
        inner = i == 0
        if kind == 'vector':
            cls = 'VectorBasicType' if basic else 'VectorCompositeType'
            t = f'new ssz.{cls}({t}, {n})'
        elif kind == 'list':
            if inner and bytes_elem and sh.base == ('uint', 8):
                t = f'new ssz.ByteListType({n})'
            else:
                cls = 'ListBasicType' if basic else 'ListCompositeType'
                t = f'new ssz.{cls}({t}, {n})'
        else:
            opts = f'{{limit: {n}}}' if n else ''
            if inner and bytes_elem and sh.base == ('uint', 8):
                t = f'new ssz.ProgressiveByteListType({opts})'
            else:
                cls = 'ProgressiveListBasicType' if basic else 'ProgressiveListCompositeType'
                t = f'new ssz.{cls}({t}{", " + opts if opts else ""})'
        basic = False
    return t


def ordered(structs, order, keep):
    """The kept structs with every struct after the ones its fields use,
    as the module defines each type before the containers that hold it."""
    out, done = [], set()

    def visit(name):
        if name in done or name not in structs:
            return
        done.add(name)
        for _, typ, _ in structs[name]:
            for dep in re.findall(r'\b([A-Z]\w*)\b', typ):
                if dep in keep and dep != name:
                    visit(dep)
        out.append(name)
    for name in order:
        if name in keep:
            visit(name)
    return out


def emit(aliases, structs, order, keep, presets):
    out = ['// Generated by baselines/convert_foreign.py ts from the harness types: do not edit.',
           f'import * as ssz from "{SSZ_IMPORT}";',
           '',
           '// The basic types, shared by the presets. uint64 reads 2^64-1 as',
           '// Infinity (clipInfinity), the only way a double serializes it back.',
           'const uint8 = new ssz.UintNumberType(1);',
           'const uint16 = new ssz.UintNumberType(2);',
           'const uint32 = new ssz.UintNumberType(4);',
           'const uint64 = new ssz.UintNumberType(8, {clipInfinity: true});',
           'const uint256 = new ssz.UintBigintType(32);',
           'const boolean = new ssz.BooleanType();',
           '']
    for preset in presets:
        out.append(f'export const {preset.name} = (() => {{')
        for name in ordered(structs, order, keep):
            fields = structs[name]
            progressive = any('ssz-index' in t for _, _, t in fields)
            cls = 'ProgressiveContainerType' if progressive else 'ContainerType'
            out.append(f'  const {name} = new ssz.{cls}({{')
            for fname, typ, tags in fields:
                sh = shape(typ, tags, aliases, preset)
                out.append(f'    {fname}: {js_type(sh, is_bytes(typ, aliases))},')
            if progressive:
                active = ', '.join('true' for _ in fields)
                out.append(f'  }}, [{active}], {{typeName: "{name}"}});')
            else:
                out.append(f'  }}, {{typeName: "{name}"}});')
        names = ', '.join(ordered(structs, order, keep))
        out.append(f'  return {{{names}}};')
        out.append('})();')
        out.append('')
    return '\n'.join(out)
